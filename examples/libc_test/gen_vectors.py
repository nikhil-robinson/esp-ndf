"""Reference vectors for examples/libc_test: IEEE float32 divide, sqrt,
conversions, computed by numpy on the host (exact IEEE rounding).
Run: python3 gen_vectors.py > vectors.h"""
import numpy as np
rng = np.random.default_rng(12345)
N = 1500
def rand_bits(n):
    b = rng.integers(0, 2**32, n, dtype=np.uint64).astype(np.uint32)
    # bias exponents toward interesting ranges: a third near 1, a third denormal/huge edges
    e = rng.integers(0, 3, n)
    near = (b & 0x807FFFFF) | (rng.integers(100, 155, n, dtype=np.uint32) << 23)
    edge = (b & 0x807FFFFF) | (rng.choice([0, 1, 2, 253, 254], n).astype(np.uint32) << 23)
    return np.where(e == 0, near, np.where(e == 1, edge, b)).astype(np.uint32)
spec = np.array([0, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 1, 0x80000001, 0x7F7FFFFF, 0x00800000,
                 0x3F800000, 0x40000000, 0x3F7FFFFF, 0x3F800001, 0x40490FDB, 0x007FFFFF], dtype=np.uint32)
a = np.concatenate([spec.repeat(len(spec)), rand_bits(N)])
b = np.concatenate([np.tile(spec, len(spec)), rand_bits(N)])
with np.errstate(all='ignore'):
    q = (a.view(np.float32) / b.view(np.float32)).view(np.uint32)
    s = np.sqrt(np.abs(a.view(np.float32))).view(np.uint32)
    d = a.view(np.float32).astype(np.float64).view(np.uint64)
    # double -> float: random doubles
    dd = rng.integers(0, 2**63, N, dtype=np.uint64) | (rng.integers(0, 2, N, dtype=np.uint64) << 63)
    ddexp = rng.integers(1023 - 160, 1023 + 140, N, dtype=np.uint64)
    dd = (dd & np.uint64(0x800FFFFFFFFFFFFF)) | (ddexp << np.uint64(52))
    df = dd.view(np.float64).astype(np.float32).view(np.uint32)
    ll = rng.integers(-2**63, 2**63 - 1, N, dtype=np.int64) >> rng.integers(0, 63, N)
    lf = ll.astype(np.float32).view(np.uint32)
def arr(name, t, v, fmt):
    print(f"static const {t} {name}[{len(v)}] = {{")
    for i in range(0, len(v), 8): print("  " + ", ".join(fmt(int(x)) for x in v[i:i+8]) + ",")
    print("};")
print("/* generated by gen_vectors.py: IEEE reference results from numpy */")
print("#define NV %d\n#define ND %d" % (len(a), N))
h = lambda x: "0x%08x" % x
H = lambda x: "0x%016xull" % x
arr("va", "uint32_t", a, h); arr("vb", "uint32_t", b, h); arr("vq", "uint32_t", q, h); arr("vs", "uint32_t", s, h)
arr("vd", "uint64_t", d, H); arr("dd", "uint64_t", dd, H); arr("df", "uint32_t", df, h)
arr("ll", "int64_t", ll, lambda x: "%dll" % x if x != -2**63 else "(-9223372036854775807ll - 1)"); arr("lf", "uint32_t", lf, h)

# printf cases: (format, double value) -> expected string, from Python's C-style %
import struct
fcases = [("%f", 3.14159265358979), ("%.2f", 2.675), ("%.0f", 0.5), ("%.0f", 1.5), ("%.0f", 2.5), ("%.3f", -0.0005),
          ("%10.4f", 3.14159), ("%-10.2f|", 1.005), ("%+.1f", 9.95), ("%08.3f", -3.5), ("%f", 0.0), ("%f", -0.0),
          ("%.10f", 1e-10), ("%f", 123456789.125), ("%e", 12345.678), ("%.3e", 0.000123456), ("%E", 1e100),
          ("%e", 0.0), ("%.0e", 9.5), ("%e", 1e-300), ("%g", 100000.0), ("%g", 1000000.0), ("%g", 0.0001),
          ("%g", 0.00001), ("%g", 3.14159265), ("%.3g", 0.0009995), ("%.10g", 1.0/3), ("%g", 0.0), ("%G", 1e-20),
          ("%f", float('inf')), ("%f", float('-inf')), ("%f", float('nan')), ("%.1f", 0.05), ("%.1f", 0.25),
          ("%.2f", 1e15 + 0.3), ("%g", 1e300), ("%.17g", 0.1), ("%.6f", 2.0**-20), ("%5.1f%%", 99.95)]
print("static const struct { const char *fmt; double v; const char *want; } fcase[] = {")
for f, v in fcases:
    w = f % v
    w = w.replace("inf", "inf").replace("nan", "nan")
    bits = struct.unpack('<Q', struct.pack('<d', v))[0]
    print('  { "%s", %s, "%s" },' % (f.replace('%', '%'), "__builtin_inf()" if v == float('inf') else "-__builtin_inf()" if v == float('-inf') else "__builtin_nan(\"\")" if v != v else repr(v), w))
print("};")
