"""P-256 vectors for components/drivers/crypto/test_apps/p256_test and bench/idf_p256 (python cryptography + plain-int ECDSA with a fixed k)."""
import hashlib
from cryptography.hazmat.primitives.asymmetric import ec, utils
from cryptography.hazmat.primitives import hashes
P = 2**256 - 2**224 + 2**192 + 2**96 - 1
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
def be(v): return v.to_bytes(32, 'big')
def arr(name, b): return f"static const uint8_t {name}[{len(b)}] = {{ " + ", ".join(f"0x{x:02x}" for x in b) + " };"
def pub(k): n = k.public_key().public_numbers(); return be(n.x) + be(n.y)
d = 0xC9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721   # RFC 6979 A.2.5 key
k1 = ec.derive_private_key(d, ec.SECP256R1()); k2 = ec.derive_private_key(0x1234567890ABCDEF * 7919 + 3, ec.SECP256R1())
msg = b"sample"; h = hashlib.sha256(msg).digest(); e = int.from_bytes(h, 'big') % N
k = 0xA6E3C57DD01ABE90086538398355DD4C3B17AA873382B0F24D6129493D8AAD60   # RFC 6979 k for SHA-256 "sample"
G = ec.derive_private_key(k, ec.SECP256R1()).public_key().public_numbers()
r = G.x % N; s = pow(k, -1, N) * (e + r * d) % N
assert (r, s) == (0xEFD48B2AACB6A8FD1140DD9CD45E81D69D2C877B56AAF991C34D0EA84EAF3716, 0xF7CB1C942D657C41D436C7A1B6E29F65F3E900DBB9AFF4064DC4AB2F843ACDA8)
der = k1.sign(h, ec.ECDSA(utils.Prehashed(hashes.SHA256()))); pr, ps = utils.decode_dss_signature(der)
shared = k1.exchange(ec.ECDH(), k2.public_key())
out = ["/* generated by gen_vectors.py */", arr("v_priv", be(d)), arr("v_pub", pub(k1)), arr("v_priv2", be(k2.private_numbers().private_value)),
       arr("v_pub2", pub(k2)), arr("v_shared", shared), arr("v_hash", h), arr("v_k", be(k)), arr("v_sig_k", be(r) + be(s)),
       arr("v_sig_py", be(pr) + be(ps))]
open(__file__.replace("gen_vectors.py", "vectors.h"), "w").write("\n".join(out) + "\n")
