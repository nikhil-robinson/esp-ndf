"""AES-GCM vectors for components/drivers/crypto/test_apps/gcm_test and bench/idf_gcm: tags (+ first ciphertext block) from python cryptography.
Plaintext byte i = (i * 7 + 3) & 255, AAD byte i = i ^ 0x5a, key byte i = i + 1, IV byte i = 0xa0 + i."""
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
cases = [(16, 12, 20, 0), (16, 12, 20, 15), (16, 12, 0, 64), (16, 12, 20, 1000), (32, 12, 13, 1000), (16, 16, 20, 100),
         (16, 12, 20, 16384), (32, 12, 20, 16384)]
out = ["/* generated by gen_vectors.py: key bytes, iv bytes, aad, len, tag, first 16 ciphertext bytes */",
       "typedef struct { int kl, il, al, len; uint8_t tag[16], c0[16]; } gcm_vec_t;", "static const gcm_vec_t gcm_vec[] = {"]
for kl, il, al, n in cases:
    key = bytes(i + 1 for i in range(kl)); iv = bytes(0xa0 + i for i in range(il))
    aad = bytes(i ^ 0x5a for i in range(al)); pt = bytes((i * 7 + 3) & 255 for i in range(n))
    ct = AESGCM(key).encrypt(iv, pt, aad); tag = ct[-16:]; c0 = ct[:-16][:16].ljust(16, b"\0")
    h = lambda b: "{ " + ", ".join(f"0x{x:02x}" for x in b) + " }"
    out.append(f"    {{ {kl}, {il}, {al}, {n}, {h(tag)}, {h(c0)} }},")
out.append("};")
open(__file__.replace("gen_vectors.py", "vectors.h"), "w").write("\n".join(out) + "\n")
