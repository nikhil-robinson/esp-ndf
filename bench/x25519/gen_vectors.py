"""X25519 vectors for components/drivers/crypto/test_apps/x25519_test and bench/idf_x25519: two key pairs and their shared secret (python
cryptography), plus RFC 7748 5.2 vector 1."""
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives import serialization as s
raw = lambda k: k.private_bytes(s.Encoding.Raw, s.PrivateFormat.Raw, s.NoEncryption())
pub = lambda k: k.public_key().public_bytes(s.Encoding.Raw, s.PublicFormat.Raw)
a = X25519PrivateKey.from_private_bytes(bytes(range(1, 33))); b = X25519PrivateKey.from_private_bytes(bytes(range(100, 132)))
rk = bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
ru = bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
ro = bytes.fromhex("c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552")
arr = lambda n, b: f"static const uint8_t {n}[32] = {{ " + ", ".join(f"0x{x:02x}" for x in b) + " };"
out = ["/* generated by gen_vectors.py */", arr("v_a", raw(a)), arr("v_apub", pub(a)), arr("v_b", raw(b)), arr("v_bpub", pub(b)),
       arr("v_shared", a.exchange(b.public_key())), arr("v_rk", rk), arr("v_ru", ru), arr("v_ro", ro)]
open(__file__.replace("gen_vectors.py", "vectors.h"), "w").write("\n".join(out) + "\n")
