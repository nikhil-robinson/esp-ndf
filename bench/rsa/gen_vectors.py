#!/usr/bin/env python3
"""RSA accelerator test vectors: odd moduli (top bit set), random base, e = 65537 and a full-size exponent; expected
x^y mod m and x*y mod m from Python's pow(). Writes bench/rsa/vectors.h (fixed seed: reproducible)."""
import random
random.seed(20261024)
def words(v, n): return [(v >> (32 * i)) & 0xFFFFFFFF for i in range(n)]
def arr(name, v, n): return 'static const uint32_t %s[%d] = { %s };\n' % (name, n, ', '.join('0x%08x' % w for w in words(v, n)))
out = ['/* generated by bench/rsa/gen_vectors.py */\n']
for bitsz in (1024, 2048, 4096):
    n = bitsz // 32
    m = random.getrandbits(bitsz) | (1 << (bitsz - 1)) | 1
    x = random.getrandbits(bitsz) % m; y = random.getrandbits(bitsz) % m; d = random.getrandbits(bitsz) % m
    for nm, v in (('m', m), ('x', x), ('y', y), ('d', d), ('pub', pow(x, 65537, m)), ('priv', pow(x, d, m)), ('mul', x * y % m)):
        out.append(arr('v%d_%s' % (bitsz, nm), v, n))
open('bench/rsa/vectors.h', 'w').write(''.join(out))
print('ok')
