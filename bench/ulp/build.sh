#!/bin/sh
# assemble bench/ulp/ulp_count.S for the ULP-RISC-V (rv32imc, linked at 0) into bench/ulp/ulp_count.h
cd "$(dirname "$0")"
T=$HOME/.espressif/tools/riscv32-esp-elf/esp-13.2.0_20250707/riscv32-esp-elf/bin/riscv32-esp-elf
$T-gcc -march=rv32imc -mabi=ilp32 -nostdlib -Wl,-Ttext=0 -Wl,-e,0 -o /tmp/ulp_count.elf ulp_count.S && $T-objcopy -O binary /tmp/ulp_count.elf /tmp/ulp_count.bin &&
python3 -c "
b=open('/tmp/ulp_count.bin','rb').read()
print('/* generated by bench/ulp/build.sh from ulp_count.S */')
print('static const unsigned char ulp_count_bin[%d] __attribute__((aligned(4))) = {' % len(b))
print(', '.join('0x%02x' % x for x in b))
print('};')" > ulp_count.h && echo ok $(stat -c %s /tmp/ulp_count.bin) bytes
# ULP-FSM: assemble bench/ulp/ulp_fsm_count.S (esp32s3) into bench/ulp/ulp_fsm_count.h
A=$HOME/.espressif/tools/esp32ulp-elf/2.38_20240113/esp32ulp-elf/bin/esp32ulp-elf
$A-as --mcpu=esp32s3 -o /tmp/ulp_fsm.o ulp_fsm_count.S && $A-objcopy -O binary -j .text /tmp/ulp_fsm.o /tmp/ulp_fsm.bin &&
python3 -c "
b=open('/tmp/ulp_fsm.bin','rb').read()
print('/* generated by bench/ulp/build.sh from ulp_fsm_count.S */')
print('static const unsigned char ulp_fsm_count_bin[%d] __attribute__((aligned(4))) = {' % len(b))
print(', '.join('0x%02x' % x for x in b))
print('};')" > ulp_fsm_count.h && echo fsm ok $(stat -c %s /tmp/ulp_fsm.bin) bytes
