#!/usr/bin/env python3
"""Generate the init replay table (drivers/rf/rf_init_replay_<board>.h) from
an idf_rftrace log (phase 1) and an idf_phydump PHY-only register dump.

  python3 gen_init.py trace.txt table_named.txt init_regs.json out.h

Contents:
  rf_init_digital: registers the vendor init leaves set (first alias of each
     block only; ports, readbacks and live counters excluded)
  rf_init_ops: every analog-bus write, pbus write, gain-memory write and pbus
     force-mode change of the init, in trace order
These values include this chip's calibration results: valid for the board
the trace was taken on until our own calibrations replace them.
"""
import json
import sys

trace, table, regs_json, out = sys.argv[1:5]
I2C_W, I2C_WM, PBUS_W, GAIN_W, FORCE = 0x190 // 4, 0x198 // 4, 0x1a8 // 4, 0x02c // 4, 0x19c // 4

recs = []
for l in open(trace, errors='replace'):
    p = l.split()
    if len(p) == 10 and len(p[0]) == 4:
        try:
            recs.append((int(p[0], 16), int(p[1], 16), int(p[2]), int(p[3], 16), [int(x, 16) for x in p[4:]]))
        except ValueError:
            pass

ops = []                 # (op, a, b, c, x, y): 1 analog, 2 pbus, 3 gain, 4 force mode
phase = None
for idx, depth, done, ret, a in recs:
    if idx == 0xFFFF:
        phase = a[0]
        continue
    if phase != 1:
        continue
    if idx == I2C_W:
        ops.append((1, a[0] & 0xff, a[2] & 0xff, 0x70, a[3] & 0xff, 0))
    elif idx == I2C_WM:
        ops.append((1, a[0] & 0xff, a[2] & 0xff, (a[3] & 7) << 4 | (a[4] & 7), a[5] & 0xff, 0))
    elif idx == PBUS_W:
        ops.append((2, a[0] & 0xff, a[1] & 0xff, 0, a[2] & 0xffff, 0))
    elif idx == GAIN_W:
        ops.append((3, a[2] & 0xff, 0, 0, a[0], a[1]))
    elif idx == FORCE:
        ops.append((4, a[0] & 0xff, 0, 0, 0, 0))

d = json.load(open(regs_json))
post = {int(k, 16): v for k, v in d['post'].items()}
EXCLUDE = [(0x600060C8, 0x600060CC), (0x60006104, 0x60006104), (0x60006114, 0x60006124),
           (0x60008044, 0x60008044), (0x60033C0C, 0x60033C0C), (0x60033D40, 0x60033DFC)]
digital = []
for addr in d['init']:
    if 0x60006200 <= addr < 0x60007000:      # FE aliases (0x200 repeat)
        continue
    if 0x60035400 <= addr < 0x60036000:      # MAC page aliases (0x400 repeat)
        continue
    if any(lo <= addr <= hi for lo, hi in EXCLUDE):
        continue
    digital.append((addr, post[addr]))

n = [sum(o[0] == k for o in ops) for k in (1, 2, 3, 4)]
with open(out, 'w') as f:
    f.write('/* generated by bench/idf_rftrace/gen_init.py: vendor PHY init as data\n'
            ' * (%d digital words; %d analog, %d pbus, %d gain-memory writes, %d force-mode changes).\n'
            ' * Includes per-chip calibration results: valid only on the board traced. */\n'
            % (len(digital), *n))
    f.write('#pragma once\n#include "rf_init.h"\n\n')
    f.write('static const rf_reg_t rf_init_digital[%d] = {\n' % len(digital))
    for a, v in digital:
        f.write('    { 0x%08X, 0x%08X },\n' % (a, v))
    f.write('};\n\nstatic const rf_op_t rf_init_ops[%d] = {\n' % len(ops))
    for o in ops:
        f.write('    { %d, 0x%02X, 0x%02X, 0x%02X, 0x%X, 0x%X },\n' % o)
    f.write('};\n')
print('digital %d, analog %d, pbus %d, gain %d, force %d' % (len(digital), *n))
