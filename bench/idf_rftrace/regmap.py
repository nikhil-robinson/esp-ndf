#!/usr/bin/env python3
"""Analog-bus register map from vendor init traces: for every (block, reg) the
init steps that write it (nearest enclosing ROM call), the bits written, and
the final value per chip; meanings established by our own measurements are
merged from KNOWN.  python3 regmap.py table_named.txt trace_a.txt [trace_b.txt ...] > ../../docs/RF_REGMAP.md"""
import sys
from collections import OrderedDict, defaultdict
KNOWN = {
    (0x62, 0x00): 'PLL cal control: [6] start-cal mux, [5] cal pulse',
    (0x62, 0x01): 'VCO cap [7:0] (rf_pll)', (0x62, 0x02): 'VCO cap [8] at bit 4 (rf_pll)',
    (0x62, 0x05): 'VCO cap found by hardware cal [7:0] (read)', (0x62, 0x07): '[1] cal done, [2] cap bit 8 (read)',
    (0x62, 0x0B): '[6] PLL cal mux (0 during cal)', (0x62, 0x0C): 'VCO control-voltage comparator: 0 in window, 4 low, 8 high (read)',
    (0x63, 0x00): 'divider latch: 0x07 write, 0x17 latch', (0x63, 0x03): 'divider N integer', (0x63, 0x04): 'divider N fraction [15:8]',
    (0x63, 0x05): 'divider N fraction [7:0]', (0x65, 0x00): '[4] receive LO 6/5 divider path (rf_tune_rx_khz)',
    (0x67, 0x00): '[6] TX->RX loopback switch (rf_loopback)',
    (0x67, 0x14): 'RX filter, RC-cal dependent (rf_rc_cal adds code-0x23)', (0x67, 0x15): 'RX filter, RC-cal dependent',
    (0x67, 0x16): 'RX filter, RC-cal dependent', (0x67, 0x17): 'RX filter, RC-cal dependent', (0x67, 0x1C): 'RX filter, RC-cal dependent',
    (0x67, 0x1D): 'RX filter, RC-cal dependent', (0x67, 0x1E): 'RX filter, RC-cal dependent', (0x67, 0x1F): 'RX filter, RC-cal dependent',
    (0x69, 0x03): 'SAR2 init code [7:0] (constant 0x578)', (0x69, 0x04): 'SAR2 init code [10:8] at [4:3]',
    (0x69, 0x06): 'bit 3 toggled on every init', (0x6A, 0x04): 'RC cal: [0] enable, [3] start, [7:4] config',
    (0x6A, 0x05): 'RC cal code [5:0] (read; dithers +-1, settle 10 us)', (0x61, 0x08): '[2] RC cal enable',
    (0x6B, 0x01): 'TX cap per channel (set at tune)', (0x6B, 0x02): 'TX cap per channel (set at tune)',
}
BLOCK = {0x61: '?', 0x62: 'RF PLL (VCO, cal)', 0x63: 'RF PLL divider', 0x64: '?', 0x65: 'LO / receive mixer', 0x66: 'BBPLL', 0x67: 'RX front end / filters',
         0x68: '?', 0x69: 'SAR2 / temperature / LDO', 0x6A: 'BBPLL (2) / RC cal', 0x6B: 'TX (PA, caps)', 0x6C: '?', 0x6D: '?'}
names = {}
for l in open(sys.argv[1]):
    p = l.split(); names[int(p[0], 16) // 4] = p[2].replace('rom_', '').replace('app:', '')
I2C = ('i2c_writeReg', 'i2c_writeReg_Mask')
regs = defaultdict(lambda: {'ctx': OrderedDict(), 'bits': set(), 'final': {}})
for ti, tr in enumerate(sys.argv[2:]):
    ph = None; ctx = 'init'; model = {}
    for l in open(tr, errors='replace'):
        p = l.split()
        if len(p) != 10 or len(p[0]) != 4: continue
        try: idx = int(p[0], 16); d = int(p[1], 16); a = [int(x, 16) for x in p[4:]]
        except ValueError: continue
        if idx == 0xFFFF: ph = a[0]; continue
        if ph != 1: continue
        n = names.get(idx, hex(idx))
        if n not in I2C and not n.startswith('i2c') and not n.startswith('pbus') and d == 0 and n not in ('abs_temp', 'phy_byte_to_word', 'write_gain_mem', 'read_sar_dout', 'linear_to_db', 'iq_est_disable', 'dc_iq_est', 'get_data_sat'):
            ctx = n
        if n in I2C:
            b, r = a[0] & 0xff, a[2] & 0xff
            if n == 'i2c_writeReg': msb, lsb, v = 7, 0, a[3] & 0xff
            else: msb, lsb, v = a[3] & 7, a[4] & 7, a[5] & 0xff
            m = ((1 << (msb - lsb + 1)) - 1) << lsb
            model[(b, r)] = (model.get((b, r), 0) & ~m) | ((v << lsb) & m)
            e = regs[(b, r)]; e['ctx'][ctx] = 1; e['bits'].add('%d:%d' % (msb, lsb) if (msb, lsb) != (7, 0) else 'all')
    for k, v in model.items(): regs[k]['final'][ti] = v
chips = [t.split('_')[-1].split('.')[0] for t in sys.argv[2:]]
print('# ESP32-S3 analog register bus (regi2c) map\n')
print('Generated by `bench/idf_rftrace/regmap.py` from the vendor PHY init traces of %s (`bench/idf_rftrace/data`).' % ', '.join(chips))
print('"Init steps" = the ROM routine the write happened under; "final" = value the vendor init leaves.')
print('Meanings are listed only where our own code or measurements established them; the rest is open.\n')
print('Bus protocol and masters: see `drivers/rf/rf_regi2c.c`. %d registers in %d blocks are written by the init.\n' % (len(regs), len({b for b, _ in regs})))
for b in sorted({b for b, _ in regs}):
    print('## Block 0x%02X: %s\n' % (b, BLOCK.get(b, '?')))
    print('| Reg | Bits written | Final (%s) | Init steps | Meaning |' % ' / '.join(chips))
    print('|---|---|---|---|---|')
    for (bb, r) in sorted(k for k in regs if k[0] == b):
        e = regs[(bb, r)]
        fin = ' / '.join(('%02X' % e['final'][i]) if i in e['final'] else '—' for i in range(len(chips)))
        diff = len({e['final'].get(i) for i in range(len(chips))}) > 1
        steps = ', '.join(list(e['ctx'])[:4]) + (' …' if len(e['ctx']) > 4 else '')
        print('| 0x%02X | %s | %s%s | %s | %s |' % (r, ' '.join(sorted(e['bits'])), fin, ' **chip-specific**' if diff else '', steps, KNOWN.get((bb, r), '')))
    print()
