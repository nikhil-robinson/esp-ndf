#!/usr/bin/env python3
"""Emulate libphy set_pbus_mem (phy_pbus.o, IDF 5.3.5 S3) from its disassembly:
print the pbus-memory contents (address 0x200 + i, written through the gain-memory
port 0x600060CC/C8) and the range fields it puts in 0x600060E0..F4, as C tables."""
ro = bytes.fromhex(  # phy_pbus.o .rodata
    '00010001000100 01ff090700ff131700'.replace(' ', '') +
    '0000f5000000f600ff010400ff011800' + 'ff011400ff030400fff91400ff011800' +
    'ff0148000000f0000000f1000000f200' + '0000f400fff91400ffff44000000f300' + 'ff014400ff015400')
def w(off): return int.from_bytes(ro[off:off + 4], 'big')   # objdump prints bytes in memory order
def le(off): return int.from_bytes(ro[off:off + 4], 'little')
st = {}
st[80], st[84], st[88], st[92] = le(8), le(12), le(16), le(20)
st[156], st[160], st[164] = le(0x18), le(0x1c), le(0x20)
for i in range(8): st[32 + 4 * i] = le(0x24 + 4 * i)
st[152], st[144], st[148] = le(0x20), le(0x18), le(0x1c)
st[132], st[136], st[140] = le(0x44), le(0x48), le(0x4c)
st[176], st[180] = le(0x50), le(0x54)
st[64], st[72], st[76] = st[80], st[88], st[92]
st[120], st[124], st[128] = 0x401ff, 0x1801ff, 0x1401ff
for i in range(8): st[4 * i] = st[32 + 4 * i]
st[108], st[112], st[116] = 0x401ff, 0x1801ff, 0x1401ff
st[100], st[104], st[168], st[172], st[68], st[96], st[12] = 0x44ffff, 0xf30000, 0x4401ff, 0x5401ff, 0x1717ff, 0x14fdff, 0x4831ff
E0, E4, E8, EC, F0, F4 = 0x600060E0, 0x600060E4, 0x600060E8, 0x600060EC, 0x600060F0, 0x600060F4
groups = [(80, 4, 0, E0), (156, 3, 16, E0), (32, 8, 0, E4), (144, 3, 16, E4), (132, 3, 0, E8), (176, 2, 16, E8),
          (64, 4, 0, EC), (120, 3, 16, EC), (0, 8, 0, F0), (108, 3, 16, F0), (96, 3, 0, F4), (168, 2, 16, F4)]
regs = {}; mem = []; a2 = 0
for sp, n, sh, reg in groups:
    end = a2 + n
    field = (((end - 1) << 8) | a2) & 0xFFFF
    regs[reg] = (regs.get(reg, 0) & ~(0xFFFF << sh)) | field << sh
    for k in range(n): mem.append((0x200 + a2 + k, st[sp + 4 * k]))
    a2 = end
print('/* generated by tools/gen_pbus_mem.py: libphy set_pbus_mem, emulated */')
print('static const uint32_t rf_pbus_mem[%d] = {' % len(mem))
for i in range(0, len(mem), 4): print('    ' + ' '.join('0x%08X,' % v for _, v in mem[i:i + 4]))
print('};')
print('static const struct { uint32_t a, v; } rf_pbus_mem_ranges[6] = {')
for r in sorted(regs): print('    { 0x%08X, 0x%08X },' % (r, regs[r]))
print('};')
