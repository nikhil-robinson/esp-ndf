"""Generate components/lib/pow10_table.h: 10^k as a normalised 64-bit mantissa M (top bit
set) and binary exponent E with 10^k ~= M * 2^E, rounded to nearest.
Small: k = 0..27. Large: k = 28*j for j = -14..12 (covers 1e-392..1e336)."""
from fractions import Fraction
def norm(k):
    v = Fraction(10) ** k
    e = v.numerator.bit_length() - v.denominator.bit_length() - 64
    while v / Fraction(2) ** e >= 2 ** 64: e += 1
    while v / Fraction(2) ** e < 2 ** 63: e -= 1
    m = v / Fraction(2) ** e
    mi = m.numerator // m.denominator
    rem = m - mi
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and mi & 1): mi += 1
    if mi == 2 ** 64: mi //= 2; e += 1
    return mi, e
print("/* generated by tools/gen_pow10.py: 10^k ~= m * 2^e, m normalised (bit 63 set), rounded to nearest */")
print("#define P10_SMALL 28\n#define P10_STEP 28\n#define P10_LMIN (-14)\n#define P10_LMAX 12")
print("static const struct { uint64_t m; int16_t e; } p10_small[P10_SMALL] = {")
for k in range(28):
    m, e = norm(k); print("    { 0x%016XULL, %d }," % (m, e))
print("};\nstatic const struct { uint64_t m; int16_t e; } p10_large[P10_LMAX - P10_LMIN + 1] = {")
for j in range(-14, 13):
    m, e = norm(28 * j); print("    { 0x%016XULL, %d },   /* 1e%d */" % (m, e, 28 * j))
print("};")
