#!/usr/bin/env python3
"""eFuse field table from ESP-IDF's esp_efuse_table.csv -> C (name, block, bit offset, bits).
usage: gen_efuse.py esp_efuse_table.csv out.h"""
import sys, re
rows = []
for line in open(sys.argv[1]):
    line = line.split('#')[0].strip()
    if not line: continue
    m = re.match(r'([\w.]*),\s*EFUSE_BLK(\d+),\s*(\d+),\s*(\d+),', line)
    if m:                                                  # an empty name continues the previous field (MAC rows)
        name = m.group(1) or rows[-1][0]
        rows.append((name, int(m.group(2)), int(m.group(3)), int(m.group(4))))
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools/gen_efuse.py from ESP-IDF components/efuse/esp32s3/esp_efuse_table.csv */\n')
    f.write('static const efuse_field_t efuse_fields[] = {\n')
    for n, b, o, l in rows: f.write('    { "%s", %d, %d, %d },\n' % (n, b, o, l))
    f.write('};\n')
print(len(rows), 'fields')
