#!/usr/bin/env python3
"""bench/idf_bleprobe/data/state_<chip>.txt (vendor BLE controller idle after a scan) -> drivers/ble/ble_state.h:
the BT modem block 0x60011000, the link-layer core registers 0x60031000 (status, clock, scheduler and EM-map
registers left out), the exchange-memory image and its segment map (EM offset -> position in our buffer)."""
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'bench/idf_bleprobe/data/state_c948.txt'
t = open(src).read()
t = t[t.index('== state'):t.index('== state end')]
reg = {int(a, 16): int(v, 16) for a, v in re.findall(r'^r (\w+) (\w+)', t, re.M)}
segs = [(int(k), int(o, 16), int(a, 16)) for k, o, a in re.findall(r'^seg (\d+) off (\w+) addr (\w+)', t, re.M)]
em = {}
for l in re.findall(r'^e (.*)$', t, re.M):
    w = [int(x, 16) for x in l.split()]
    for i, v in enumerate(w[1:]): em[w[0] + 4 * i] = v
skip = {0x10, 0x14, 0x18, 0x1C, 0x20, 0x24} | set(range(0x100, 0x120, 4)) | set(range(0x200, 0x2C0, 4))
core = [(a - 0x60031000, v) for a, v in sorted(reg.items()) if 0x60031000 <= a < 0x60031400 and (a - 0x60031000) not in skip
        and (v or a < 0x60031100) and a != 0x60031000]
modem = [reg[0x60011000 + 4 * k] for k in range(64)]
# pack the segments back to back (a segment's size: the gap to the next one in DRAM, at most 0x400; else 0x114)
by_addr = sorted(segs, key=lambda x: x[2])
packed, pos, img = [], 0, []
for i, (k, off, a) in enumerate(by_addr):
    gap = by_addr[i + 1][2] - a if i + 1 < len(by_addr) else 0
    size = gap if 0 < gap <= 0x400 else 0x114
    packed.append((k, off, pos))
    img += [em.get(a + j, 0) for j in range(0, size, 4)]
    pos += size
o = ['/* generated by tools/gen_ble_state.py from %s: vendor BLE controller state after a passive scan */' % src,
     '#pragma once', '#include <stdint.h>',
     'static const uint32_t ble_modem_regs[64] = {' + ', '.join('0x%08X' % v for v in modem) + '};',
     'static const uint32_t ble_rwblecntl = 0x%08X;' % reg[0x60031000],
     'static const struct { uint16_t off; uint32_t val; } ble_core_regs[] = {'] + \
    ['    { 0x%03X, 0x%08X },' % (a, v) for a, v in core] + ['};',
     '/* EM page registers 0..55, offset field only: unused pages must still carry their offset (zeros break TX) */',
     'static const uint32_t ble_em_map_off[56] = {' + ', '.join('0x%08X' % (reg.get(0x60031204 + 4 * k + (28 if k > 47 else 0), 0) & 0xFFFC0000) for k in range(56)) + '};',
     '#define BLE_EM_WORDS %d' % len(img),
     'static const struct { uint8_t idx; uint16_t em_off; uint16_t pos; } ble_em_segs[] = {'] + \
    ['    { %d, 0x%04X, 0x%04X },' % (k, off, p) for k, off, p in packed] + ['};',
     'static const uint32_t ble_em_image[BLE_EM_WORDS] = {'] + \
    ['    ' + ', '.join('0x%08X' % v for v in img[i:i + 8]) + ',' for i in range(0, len(img), 8)] + ['};']
blocks = [('coex', 0x60035000, 0x400), ('btbb', 0x6000E000, 0x200)]   # all the BLE path needs beyond core/modem/EM (bisected)
o += ['/* coex arbiter page (grants the radio to BT) and the BT baseband / analog-bus sequencer block */',
      'static const struct { uint32_t addr, val; } ble_vendor_phy[] = {']
for n, b, l in blocks: o += ['    { 0x%08X, 0x%08X },' % (a, reg[a]) for a in range(b, b + l, 4) if reg.get(a)]   # ponytail: zero-valued vendor regs left out (RAM); add if a bisect needs them
o += ['};', 'static const struct { uint32_t base, len; } ble_vendor_phy_blocks[] = {' + ', '.join('{ 0x%08X, 0x%X }' % (b, l) for _, b, l in blocks) + '};']
# advertiser control structure (CS at EM 0x400 while the vendor advertised), from the advertising capture
adv = sys.argv[2] if len(sys.argv) > 2 else 'bench/idf_bleprobe/data/state_adv_c948.txt'
ta = open(adv).read(); ta = ta[ta.index('== state'):ta.index('== state end')]
asegs = sorted((int(o, 16), int(a, 16)) for k, o, a in re.findall(r'^seg (\d+) off (\w+) addr (\w+)', ta, re.M))
amem = {}
for l in re.findall(r'^e (.*)$', ta, re.M):
    w = [int(x, 16) for x in l.split()]
    for i, v in enumerate(w[1:]): amem[w[0] + 4 * i] = v
def ard16(o):
    sg = max((x for x in asegs if x[0] <= o), key=lambda x: x[0]); a = sg[1] + o - sg[0]
    return (amem.get(a & ~3, 0) >> (8 * (a & 2))) & 0xFFFF
areg = {int(a, 16): int(v, 16) for a, v in re.findall(r'^r (\w+) (\w+)', ta, re.M)}
acore = [(a - 0x60031000, v) for a, v in sorted(areg.items()) if 0x60031000 <= a < 0x60031400 and (a - 0x60031000) not in skip
         and (v or a < 0x60031100) and a != 0x60031000]
o += ['/* core registers while the vendor advertised (differ from the scan set at 0x2CC, 0x308.., 0x32C, 0x368, 0x374) */',
      'static const struct { uint16_t off; uint32_t val; } ble_adv_core_regs[] = {'] + ['    { 0x%03X, 0x%08X },' % x for x in acore] + ['};',
      'static const uint16_t ble_adv_em14c = 0x%04X;   /* EM 0x14C: the current CS format word */' % ard16(0x14C)]
o += ['/* advertiser CS (45 half-words at EM 0x400) and TX descriptor (EM 0x1400) from ' + adv + ' */',
      'static const uint16_t ble_adv_cs[45] = {' + ', '.join('0x%04X' % ard16(0x400 + 2 * i) for i in range(45)) + '};',
      'static const uint16_t ble_adv_txdesc[9] = {' + ', '.join('0x%04X' % ard16(0x1400 + 2 * i) for i in range(9)) + '};']
open('drivers/ble/ble_state.h', 'w').write('\n'.join(o) + '\n')
print(len(core), 'core regs,', len(img) * 4, 'EM bytes,', len(segs), 'segments')
