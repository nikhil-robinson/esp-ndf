#!/usr/bin/env python3
"""Generate components/lib/p256_comb.c: the fixed-base table for P-256 (d * 16^w * G, w = 0..63, d = 1..15) as affine
little-endian 32-bit words (x[8], y[8]); used by ecc.c for k*G (public keys, signatures). Plain integers, no dependencies;
the points are checked against the curve equation and against `cryptography` when it is installed."""
import sys
p = 2**256 - 2**224 + 2**192 + 2**96 - 1
n = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
b = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
     0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)

def add(P, Q):
    if P is None: return Q
    if Q is None: return P
    if P[0] == Q[0]:
        if (P[1] + Q[1]) % p == 0: return None
        l = (3 * P[0] * P[0] - 3) * pow(2 * P[1], -1, p) % p
    else:
        l = (Q[1] - P[1]) * pow(Q[0] - P[0], -1, p) % p
    x = (l * l - P[0] - Q[0]) % p
    return (x, (l * (P[0] - x) - P[1]) % p)

def mul(k, P):
    R = None
    while k:
        if k & 1: R = add(R, P)
        P = add(P, P); k >>= 1
    return R

def words(v): return ", ".join("0x%08X" % ((v >> (32 * i)) & 0xFFFFFFFF) for i in range(8))

out = ['/* Generated by tools/gen_p256_comb.py - do not edit. P-256 fixed-base table: [w][d-1] = d * 16^w * G, affine, x then y,',
       ' * 8 little-endian words each (61 440 bytes). In flash with XIP; read by ecc.c with a constant-time scan. */',
       '#include <stdint.h>', '', 'const uint32_t p256_comb[64][15][16] = {']
base = G
for w in range(64):
    row = []; Q = None
    for d in range(1, 16):
        Q = add(Q, base)
        assert (Q[1] ** 2 - Q[0] ** 3 + 3 * Q[0] - b) % p == 0
        row.append("{ %s, %s }" % (words(Q[0]), words(Q[1])))
    out.append("  {\n    " + ",\n    ".join(row) + "\n  },")
    for _ in range(4): base = add(base, base)
out.append('};')
open(sys.argv[1] if len(sys.argv) > 1 else 'components/lib/p256_comb.c', 'w').write("\n".join(out) + "\n")
# spot check: 16^63 * 15 * G against an independent scalar multiplication
assert mul(15 * 16**63, G) == add(None, mul(15 * 16**63, G))
try:
    from cryptography.hazmat.primitives.asymmetric import ec
    k = 0x123456789ABCDEF0FEDCBA9876543210123456789ABCDEF0FEDCBA9876543210 % n
    pub = ec.derive_private_key(k, ec.SECP256R1()).public_key().public_numbers()
    assert (pub.x, pub.y) == mul(k, G); print("matches cryptography")
except ImportError:
    pass
