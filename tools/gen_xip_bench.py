#!/usr/bin/env python3
"""Generate bench/xip/xip_kern.c: N distinct integer kernels (~380 B of code each), shared by examples/xip_test and the
IDF sibling bench/idf_xip, so both run the same code from flash. Total code ~ N * 380 B (64 -> ~24 KB: more than IDF's
16 KB instruction cache, less than esp-ndf's 32 KB). Usage: gen_xip_bench.py [N]"""
import sys, random
N = int(sys.argv[1]) if len(sys.argv) > 1 else 64
random.seed(1)
ops = ['x = x * {c}u + {d}u;', 'x ^= x >> {s};', 'x ^= x << {t};', 'x += (x >> {s}) * {c}u;', 'x = (x << {s}) | (x >> (32 - {s}));']
out = ['/* generated by tools/gen_xip_bench.py %d: do not edit. Include with XK_ATTR (placement) and XK_P (name prefix). */' % N,
       '#include <stdint.h>', '#ifndef XK_ATTR', '#define XK_ATTR', '#endif', '#ifndef XK_P', '#define XK_P xk', '#endif',
       '#define XK_C2(a, b) a##_##b', '#define XK_C(a, b) XK_C2(a, b)']
for i in range(N):
    body = [random.choice(ops).format(c=random.randrange(3, 1 << 20) | 1, d=random.randrange(1 << 16), s=random.randrange(1, 31), t=random.randrange(1, 31)) for _ in range(40)]
    out.append('XK_ATTR uint32_t XK_C(XK_P, %d)(uint32_t x) { %s return x; }' % (i, ' '.join(body)))
out.append('uint32_t (*const XK_C(XK_P, table)[%d])(uint32_t) = { %s };' % (N, ', '.join('XK_C(XK_P, %d)' % i for i in range(N))))
out.append('#define XK_COUNT %d' % N)
open('bench/xip/xip_kern.c', 'w').write('\n'.join(out) + '\n')
