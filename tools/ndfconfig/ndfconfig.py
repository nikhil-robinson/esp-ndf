#!/usr/bin/env python3
"""esp-ndf menuconfig: nested, searchable, themed terminal configurator.

  ndfconfig.py <app_dir>                      interactive (curses)
  ndfconfig.py <app_dir> --list               every option: key = value (* = changed)
  ndfconfig.py <app_dir> --get KEY
  ndfconfig.py <app_dir> --set KEY=VALUE ...  validate, save
  ndfconfig.py <app_dir> --reset KEY ...      back to default, save
  ndfconfig.py --doc [out.md]                 generate docs/CONFIG.md from the schema

Writes only non-default values: <app>/ndf_config.h (C options) and
<app>/app.mk (build options). Hand-written files are read back in, and
backed up as .bak before the first overwrite.

Keys (interactive): arrows/hjkl move and open, Enter/Space toggle or edit,
/ search, c changes only, r reset to default, t theme, s save, q quit, ? help.
"""
import os, re, sys, json, curses, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from schema import SCHEMA  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
MARK = 'Generated by esp-ndf menuconfig (tools/ndfconfig). Edit with "make menuconfig".'
PREFS = os.path.expanduser('~/.config/esp-ndf/menuconfig.json')

# ---- model ------------------------------------------------------------------

class Option:
    def __init__(self, d, path):
        self.__dict__.update(d)
        self.path = path
        self.value = d['default']

    @property
    def changed(self):
        return self.value != self.default

    def fmt(self, v=None):
        v = self.value if v is None else v
        if self.type == 'bool':
            return 'y' if v else 'n'
        if self.type == 'hex':
            return '0x%X' % v
        return str(v)

    def label_of(self, v):
        for val, lab in getattr(self, 'choices', []):
            if val == v:
                return lab
        return str(v)

    def parse(self, text):
        """text -> value, or raise ValueError with a reason"""
        t = text.strip()
        if self.type == 'bool':
            if t.lower() in ('y', 'yes', '1', 'true', 'on'):
                return True
            if t.lower() in ('n', 'no', '0', 'false', 'off', ''):
                return False
            raise ValueError('expected y/n')
        if self.type in ('int', 'hex'):
            v = int(t, 0)
            lo, hi = getattr(self, 'range', (None, None))
            if lo is not None and not lo <= v <= hi:
                raise ValueError('out of range %s..%s' % (self.fmt(lo), self.fmt(hi)))
            return v
        if self.type == 'choice':
            vals = [c[0] for c in self.choices]
            if t in vals:
                return t
            for val, lab in self.choices:          # accept a unique prefix of the label too
                if lab.lower().startswith(t.lower()) and t:
                    return val
            raise ValueError('one of: ' + ', '.join(vals))
        return t


class Menu:
    def __init__(self, title, items, path):
        self.title, self.items, self.path = title, items, path


def build(node, path=()):
    _, title, items = node
    out = []
    for it in items:
        if isinstance(it, tuple):
            out.append(build(it, path + (it[1],)))
        else:
            out.append(Option(it, path))
    return Menu(title, out, path)


def all_options(menu):
    for it in menu.items:
        if isinstance(it, Menu):
            yield from all_options(it)
        else:
            yield it


def soc_caps():
    """read-only capabilities from components/soc/<chip>/soc_caps.h (accelerated build view)"""
    caps = []
    p = os.path.join(ROOT, 'components', 'soc', 'esp32s3', 'soc_caps.h')
    try:
        txt = open(p).read().split('#else')[0]
        for m in re.finditer(r'#define\s+(SOC_\w+)\s+(\S+)\s*(?:/\*\s*(.*?)\s*\*/)?', txt):
            caps.append((m.group(1), m.group(2), m.group(3) or ''))
    except OSError:
        pass
    return caps


class Config:
    def __init__(self, app):
        self.app = app
        self.root = build(SCHEMA)
        self.opts = {o.key: o for o in all_options(self.root)}
        self.h_path = os.path.join(app, 'ndf_config.h')
        self.mk_path = os.path.join(app, 'app.mk')
        self.load()
        self.saved = self.snapshot()

    def snapshot(self):
        return {k: o.value for k, o in self.opts.items()}

    @property
    def dirty(self):
        return self.snapshot() != self.saved

    def enabled(self, o):
        dep = getattr(o, 'depends', None)
        if not dep:
            return True, ''
        if isinstance(dep, tuple):
            k, v = dep
            if isinstance(v, str) and v.startswith('!'):        # ('KEY', '!value'): any value but that one
                return self.opts[k].value != v[1:], 'needs %s != %s' % (k, v[1:])
            return self.opts[k].value == v, 'needs %s = %s' % (k, v)
        return bool(self.opts[dep].value), 'needs %s' % dep

    def load(self):
        for path, rx in ((self.h_path, r'^\s*#define\s+(\w+)\s+(.*?)\s*(?:/\*.*)?$'),
                         (self.mk_path, r'^\s*(\w+)\s*[:?]?=\s*(.*?)\s*(?:#.*)?$')):
            if not os.path.exists(path):
                continue
            for line in open(path):
                m = re.match(rx, line)
                if m and m.group(1) in self.opts:
                    o = self.opts[m.group(1)]
                    raw = m.group(2).strip().strip('"')
                    try:
                        o.value = o.parse(raw)
                    except ValueError:
                        pass

    def render(self, target):
        lines = []
        for o in self.opts.values():
            if o.target != target or not o.changed:
                continue
            if target == 'h':
                v = ('1' if o.value else '0') if o.type == 'bool' else ('"%s"' % o.value if o.type == 'string' else o.fmt())
                lines.append('#define %-24s %s   /* %s */' % (o.key, v, o.label))
            else:
                v = ('1' if o.value else '0') if o.type == 'bool' else o.fmt()
                lines.append('%-16s = %s   # %s' % (o.key, v, o.label))
        return lines

    def save(self):
        for path, target, cmt in ((self.h_path, 'h', ('/* ', ' */')), (self.mk_path, 'mk', ('# ', ''))):
            body = self.render(target)
            if os.path.exists(path) and MARK not in open(path).read():
                os.replace(path, path + '.bak')                       # hand-written: keep a copy, values already loaded
            if not body:                                              # all defaults: no file needed
                if os.path.exists(path):
                    os.remove(path)
                continue
            with open(path, 'w') as f:
                f.write(cmt[0] + MARK + cmt[1] + '\n')
                if target == 'h':
                    f.write('#pragma once\n')
                f.write('\n'.join(body) + '\n')
        self.saved = self.snapshot()


# ---- docs ------------------------------------------------------------------

def gen_doc(out):
    root = build(SCHEMA)
    w = ['# esp-ndf configuration\n',
         'Generated from `tools/ndfconfig/schema.py` by `tools/ndfconfig/ndfconfig.py --doc`. Change options with '
         '`make menuconfig` in the application folder. That writes only the non-default values to `<app>/ndf_config.h` (C options) and '
         '`<app>/app.mk` (build options). Chip capabilities (what the silicon has) are in `components/soc/<chip>/soc_caps.h`.\n']

    def walk(m, depth):
        for it in m.items:
            if isinstance(it, Menu):
                w.append('\n%s %s\n' % ('#' * min(depth + 2, 4), it.title))
                w.append('| Option | File | Default | Values | Description |\n|---|---|---|---|---|')
                walk(it, depth + 1)
            else:
                if it.type == 'choice':
                    vals = '<br>'.join('`%s` %s' % c for c in it.choices)
                elif it.type in ('int', 'hex') and hasattr(it, 'range'):
                    vals = '%s – %s' % (it.fmt(it.range[0]), it.fmt(it.range[1]))
                elif it.type == 'bool':
                    vals = 'y / n'
                else:
                    vals = 'text'
                f = 'ndf_config.h' if it.target == 'h' else 'app.mk'
                w.append('| `%s`<br>%s | %s | `%s` | %s | %s |' % (it.key, it.label, f, it.fmt(it.default) or '""', vals,
                                                                   it.help.replace('|', '/')))
    walk(root, 0)
    w.append('\n## Chip capabilities (read-only, soc_caps.h)\n\n| Capability | ESP32-S3 | Meaning |\n|---|---|---|')
    for k, v, c in soc_caps():
        w.append('| `%s` | %s | %s |' % (k, v, c))
    open(out, 'w').write('\n'.join(w) + '\n')
    print('wrote', out)


# ---- terminal UI ---------------------------------------------------------------

THEMES = {   # name: (bg, fg, accent, dim, sel_bg, sel_fg, changed, title_bg, title_fg)
    'midnight': (curses.COLOR_BLACK, curses.COLOR_WHITE, curses.COLOR_CYAN, curses.COLOR_BLUE,
                 curses.COLOR_CYAN, curses.COLOR_BLACK, curses.COLOR_YELLOW, curses.COLOR_BLUE, curses.COLOR_WHITE),
    'light':    (curses.COLOR_WHITE, curses.COLOR_BLACK, curses.COLOR_BLUE, curses.COLOR_CYAN,
                 curses.COLOR_BLUE, curses.COLOR_WHITE, curses.COLOR_MAGENTA, curses.COLOR_BLUE, curses.COLOR_WHITE),
    'contrast': (curses.COLOR_BLACK, curses.COLOR_WHITE, curses.COLOR_YELLOW, curses.COLOR_WHITE,
                 curses.COLOR_YELLOW, curses.COLOR_BLACK, curses.COLOR_GREEN, curses.COLOR_WHITE, curses.COLOR_BLACK),
    'mono':     None,
}
ORDER = ['midnight', 'light', 'contrast', 'mono']
C_NORM, C_ACC, C_DIM, C_SEL, C_CHG, C_TITLE = range(1, 7)


def load_prefs():
    try:
        return json.load(open(PREFS))
    except (OSError, ValueError):
        return {}


def save_prefs(p):
    try:
        os.makedirs(os.path.dirname(PREFS), exist_ok=True)
        json.dump(p, open(PREFS, 'w'))
    except OSError:
        pass


class UI:
    def __init__(self, scr, cfg, keys=None):
        self.scr, self.cfg = scr, cfg
        self.keys = list(keys) if keys else None          # scripted key feed (tests)
        self.stack = [cfg.root]
        self.sel = [0]
        self.top = [0]
        self.msg = ''
        self.only_changed = False
        self.prefs = load_prefs()
        self.theme = self.prefs.get('theme', 'midnight')
        self.caps = soc_caps()
        curses.curs_set(0)
        self.apply_theme()

    # --- theme ---
    def apply_theme(self):
        t = THEMES.get(self.theme)
        self.mono = t is None or not curses.has_colors()
        if self.mono:
            return
        curses.start_color()
        try:
            curses.use_default_colors()
        except curses.error:
            pass
        bg, fg, acc, dim, sbg, sfg, chg, tbg, tfg = t
        curses.init_pair(C_NORM, fg, bg)
        curses.init_pair(C_ACC, acc, bg)
        curses.init_pair(C_DIM, dim, bg)
        curses.init_pair(C_SEL, sfg, sbg)
        curses.init_pair(C_CHG, chg, bg)
        curses.init_pair(C_TITLE, tfg, tbg)
        self.scr.bkgd(' ', curses.color_pair(C_NORM))

    def attr(self, c, extra=0):
        if self.mono:
            return {C_SEL: curses.A_REVERSE, C_TITLE: curses.A_REVERSE, C_ACC: curses.A_BOLD,
                    C_CHG: curses.A_BOLD | curses.A_UNDERLINE, C_DIM: curses.A_DIM}.get(c, 0) | extra
        return curses.color_pair(c) | extra

    # --- items of the current view ---
    def items(self):
        m = self.stack[-1]
        if m == 'caps':
            return [('cap', c) for c in self.caps]
        if m == 'changes':
            return [o for o in self.cfg.opts.values() if o.changed]
        if isinstance(m, tuple) and m[0] == 'search':
            return m[2]
        its = list(m.items)
        if m is self.cfg.root:
            its.append(('capsmenu', 'Chip capabilities (read-only)'))
        if self.only_changed:
            its = [i for i in its if not isinstance(i, Option) or i.changed]
        return its

    def title(self):
        m = self.stack[-1]
        crumbs = []
        for s in self.stack:
            if isinstance(s, Menu):
                crumbs.append(s.title)
            elif s == 'caps':
                crumbs.append('Chip capabilities')
            elif s == 'changes':
                crumbs.append('Changed options')
            else:
                crumbs.append('Search: ' + s[1])
        return '  ›  '.join(crumbs)

    # --- drawing ---
    def put(self, y, x, s, a=0, w=None):
        h, W = self.scr.getmaxyx()
        if y < 0 or y >= h or x >= W:
            return
        s = s[:max(0, (w if w is not None else W - x))]
        try:
            self.scr.addstr(y, x, s, a)
        except curses.error:
            pass

    def row_text(self, it, width):
        if isinstance(it, Menu):
            n = sum(1 for o in all_options(it) if o.changed)
            return '  ▸ %s' % it.title, ('  %d changed' % n if n else ''), False, True
        if isinstance(it, tuple) and it[0] == 'capsmenu':
            return '  ▸ %s' % it[1], '', False, True
        if isinstance(it, tuple) and it[0] == 'cap':
            k, v, c = it[1]
            return '    %s' % (c or k), '%s = %s' % (k, v), False, False
        o = it
        on, _ = self.cfg.enabled(o)
        if o.type == 'bool':
            box = '[x]' if o.value else '[ ]'
            return '  %s %s' % (box, o.label), '', o.changed, on
        val = o.label_of(o.value) if o.type == 'choice' else (o.fmt() or '""')
        return '      %s' % o.label, '‹ %s ›' % val, o.changed, on

    def draw(self):
        s = self.scr
        s.erase()
        h, w = s.getmaxyx()
        help_w = 40 if w >= 100 else 0
        list_w = w - help_w
        # title bar
        app = os.path.relpath(self.cfg.app, ROOT)
        head = ' esp-ndf menuconfig  ·  %s%s ' % (app, '  ·  modified' if self.cfg.dirty else '')
        self.put(0, 0, head.ljust(w), self.attr(C_TITLE, curses.A_BOLD))
        self.put(1, 1, self.title(), self.attr(C_ACC, curses.A_BOLD), list_w - 2)
        its = self.items()
        rows = h - 5
        sel = min(self.sel[-1], max(0, len(its) - 1))
        self.sel[-1] = sel
        if sel < self.top[-1]:
            self.top[-1] = sel
        if sel >= self.top[-1] + rows:
            self.top[-1] = sel - rows + 1
        if not its:
            self.put(3, 4, 'nothing here' if self.stack[-1] != 'changes' else 'all options are at their defaults',
                     self.attr(C_DIM))
        for i, it in enumerate(its[self.top[-1]:self.top[-1] + rows]):
            y = 3 + i
            left, right, changed, on = self.row_text(it, list_w)
            if isinstance(self.stack[-1], tuple) and isinstance(it, Option):
                left = '  %s' % it.label
                right = '%s  ·  %s' % (' › '.join(it.path), it.fmt() if it.type != 'choice' else it.label_of(it.value))
            idx = self.top[-1] + i
            if idx == sel:
                a = self.attr(C_SEL, curses.A_BOLD)
                self.put(y, 1, ' ' * (list_w - 2), a)
            else:
                a = self.attr(C_DIM if not on else (C_CHG if changed else C_NORM))
            self.put(y, 1, left, a, list_w - 2)
            if right:
                ra = a if idx == sel else self.attr(C_DIM if not on else (C_CHG if changed else C_ACC))
                self.put(y, max(1, list_w - 2 - len(right)), right, ra)
        # help pane
        if help_w:
            x = list_w + 1
            for y in range(1, h - 1):
                self.put(y, list_w, '│', self.attr(C_DIM))
            it = its[sel] if its else None
            lines = self.help_lines(it, help_w - 3)
            for i, (txt, a) in enumerate(lines[:h - 4]):
                self.put(2 + i, x + 1, txt, a, help_w - 3)
        # footer
        foot = ' ↑↓ move  ⏎ open/edit  ← back  / search  c changes  r reset  t theme (%s)  s save  q quit ' % self.theme
        self.put(h - 2, 0, ('  ' + self.msg).ljust(w), self.attr(C_ACC))
        self.put(h - 1, 0, foot.ljust(w), self.attr(C_TITLE))
        s.refresh()

    def help_lines(self, it, width):
        out = []
        acc, norm, dim, chg = self.attr(C_ACC, curses.A_BOLD), self.attr(C_NORM), self.attr(C_DIM), self.attr(C_CHG)
        if isinstance(it, Option):
            out.append((it.key, acc))
            out.append(('%s  ·  %s' % (it.type, 'ndf_config.h' if it.target == 'h' else 'app.mk'), dim))
            out.append(('', norm))
            out.append(('value    %s' % (it.label_of(it.value) if it.type == 'choice' else it.fmt() or '""'), chg if it.changed else norm))
            out.append(('default  %s' % (it.label_of(it.default) if it.type == 'choice' else it.fmt(it.default) or '""'), dim))
            if getattr(it, 'range', None):
                out.append(('range    %s .. %s' % (it.fmt(it.range[0]), it.fmt(it.range[1])), dim))
            on, why = self.cfg.enabled(it)
            if not on:
                out.append(('disabled: ' + why, chg))
            out.append(('', norm))
            for l in textwrap.wrap(it.help, width):
                out.append((l, norm))
        elif isinstance(it, Menu):
            out.append((it.title, acc))
            opts = list(all_options(it))
            out.append(('%d options, %d changed' % (len(opts), sum(o.changed for o in opts)), dim))
        elif isinstance(it, tuple) and it[0] == 'cap':
            k, v, c = it[1]
            out += [(k, acc), ('value %s (read-only)' % v, dim), ('', norm)] + [(l, norm) for l in textwrap.wrap(c, width)]
        elif isinstance(it, tuple) and it[0] == 'capsmenu':
            out += [('Chip capabilities', acc), ('What the silicon has (soc_caps.h).', dim),
                    ('Accelerated paths use them; NO_ACCEL', norm), ('turns them off for testing.', norm)]
        return out

    # --- input ---
    def getkey(self):
        if self.keys is not None:
            if not self.keys:
                return 'q!'
            return self.keys.pop(0)
        return self.scr.get_wch()

    def prompt(self, label, initial=''):
        h, w = self.scr.getmaxyx()
        buf = list(initial)
        while True:
            self.put(h - 2, 0, (' %s: %s' % (label, ''.join(buf))).ljust(w), self.attr(C_SEL, curses.A_BOLD))
            self.scr.refresh()
            k = self.getkey()
            if k in ('\n', '\r', curses.KEY_ENTER):
                return ''.join(buf)
            if k in ('\x1b', 'q!'):
                return None
            if k in (curses.KEY_BACKSPACE, '\x7f', '\b'):
                if buf:
                    buf.pop()
            elif isinstance(k, str) and k.isprintable():
                buf.append(k)

    def choose(self, o):
        vals = o.choices
        i = next((n for n, c in enumerate(vals) if c[0] == o.value), 0)
        while True:
            h, w = self.scr.getmaxyx()
            bw = min(w - 4, max(len(c[1]) for c in vals) + 10)
            bh = len(vals) + 2
            y0, x0 = max(2, (h - bh) // 2), max(2, (w - bw) // 2)
            for r in range(bh):
                self.put(y0 + r, x0, ' ' * bw, self.attr(C_TITLE))
            self.put(y0, x0 + 2, ' ' + o.label + ' ', self.attr(C_TITLE, curses.A_BOLD))
            for n, (v, lab) in enumerate(vals):
                a = self.attr(C_SEL, curses.A_BOLD) if n == i else self.attr(C_TITLE)
                mark = '●' if v == o.value else '○'
                self.put(y0 + 1 + n, x0 + 1, (' %s %s' % (mark, lab)).ljust(bw - 2), a)
            self.scr.refresh()
            k = self.getkey()
            if k in (curses.KEY_UP, 'k'):
                i = (i - 1) % len(vals)
            elif k in (curses.KEY_DOWN, 'j'):
                i = (i + 1) % len(vals)
            elif k in ('\n', '\r', ' ', curses.KEY_ENTER):
                return vals[i][0]
            elif k in ('\x1b', 'q', curses.KEY_LEFT, 'h', 'q!'):
                return None

    def activate(self, it):
        if isinstance(it, Menu):
            self.stack.append(it); self.sel.append(0); self.top.append(0)
            return
        if isinstance(it, tuple):
            if it[0] == 'capsmenu':
                self.stack.append('caps'); self.sel.append(0); self.top.append(0)
            return
        on, why = self.cfg.enabled(it)
        if not on:
            self.msg = 'disabled: ' + why
            return
        if it.type == 'bool':
            it.value = not it.value
        elif it.type == 'choice':
            v = self.choose(it)
            if v is not None:
                it.value = v
        else:
            t = self.prompt(it.label, it.fmt() if it.type != 'string' else it.value)
            if t is not None:
                try:
                    it.value = it.parse(t)
                    self.msg = '%s = %s' % (it.key, it.fmt() or '""')
                except ValueError as e:
                    self.msg = 'not set: %s' % e

    def search(self):
        q = self.prompt('search')
        if not q:
            return
        ql = q.lower()
        hits = [o for o in self.cfg.opts.values()
                if ql in o.key.lower() or ql in o.label.lower() or ql in o.help.lower() or ql in ' '.join(o.path).lower()]
        self.stack.append(('search', q, hits)); self.sel.append(0); self.top.append(0)
        self.msg = '%d match%s for "%s"' % (len(hits), '' if len(hits) == 1 else 'es', q)

    def run(self):
        while True:
            self.draw()
            k = self.getkey()
            its = self.items()
            cur = its[self.sel[-1]] if its else None
            self.msg = '' if k not in (curses.KEY_RESIZE,) else self.msg
            if k in (curses.KEY_UP, 'k'):
                self.sel[-1] = max(0, self.sel[-1] - 1)
            elif k in (curses.KEY_DOWN, 'j'):
                self.sel[-1] = min(len(its) - 1, self.sel[-1] + 1) if its else 0
            elif k in (curses.KEY_PPAGE,):
                self.sel[-1] = max(0, self.sel[-1] - 10)
            elif k in (curses.KEY_NPAGE,):
                self.sel[-1] = min(len(its) - 1, self.sel[-1] + 10) if its else 0
            elif k in ('\n', '\r', ' ', curses.KEY_ENTER, curses.KEY_RIGHT, 'l'):
                if cur is not None:
                    if k in (curses.KEY_RIGHT, 'l') and isinstance(cur, Option):
                        pass
                    else:
                        self.activate(cur)
            elif k in (curses.KEY_LEFT, 'h', '\x1b', curses.KEY_BACKSPACE, '\x7f'):
                if len(self.stack) > 1:
                    self.stack.pop(); self.sel.pop(); self.top.pop()
            elif k == '/':
                self.search()
            elif k == 'c':
                self.stack.append('changes'); self.sel.append(0); self.top.append(0)
            elif k == 'r' and isinstance(cur, Option):
                cur.value = cur.default
                self.msg = '%s back to default' % cur.key
            elif k == 't':
                self.theme = ORDER[(ORDER.index(self.theme) + 1) % len(ORDER)] if self.theme in ORDER else 'midnight'
                self.prefs['theme'] = self.theme
                save_prefs(self.prefs)
                self.apply_theme()
                self.msg = 'theme: ' + self.theme
            elif k == 's':
                self.cfg.save()
                self.msg = 'saved %s' % ', '.join(os.path.relpath(p, ROOT) for p in (self.cfg.h_path, self.cfg.mk_path)
                                                  if os.path.exists(p)) or 'saved (all defaults: no files needed)'
            elif k in ('q', 'q!'):
                if k == 'q' and self.cfg.dirty:
                    a = self.prompt('unsaved changes: s = save and quit, d = discard, other = stay')
                    if a == 's':
                        self.cfg.save()
                        return
                    if a == 'd':
                        return
                    continue
                return
            elif k == '?':
                self.msg = 'arrows/hjkl move · ⏎ open or edit · / search · c changed · r reset · t theme · s save · q quit'


# ---- entry -------------------------------------------------------------------

def main():
    a = sys.argv[1:]
    if not a or a[0] in ('-h', '--help'):
        print(__doc__)
        return
    if a[0] == '--doc':
        gen_doc(a[1] if len(a) > 1 else os.path.join(ROOT, 'docs', 'CONFIG.md'))
        return
    app = os.path.abspath(a[0])
    if not os.path.isdir(app):
        sys.exit('no such app directory: %s' % app)
    cfg = Config(app)
    rest = a[1:]
    if not rest:
        curses.wrapper(lambda s: UI(s, cfg).run())
        return
    if rest[0] == '--keys':                                  # scripted UI run (tests): keys as Python literals
        import ast
        keys = [getattr(curses, k) if k.startswith('KEY_') else ast.literal_eval(k) for k in rest[1:]]
        curses.wrapper(lambda s: UI(s, cfg, keys).run())
        return
    if rest[0] == '--list':
        for o in cfg.opts.values():
            print('%s %-18s = %s' % ('*' if o.changed else ' ', o.key, o.fmt()))
        return
    if rest[0] == '--get':
        for k in rest[1:]:
            print(cfg.opts[k].fmt())
        return
    if rest[0] in ('--set', '--reset'):
        for kv in rest[1:]:
            k, _, v = kv.partition('=')
            if k not in cfg.opts:
                sys.exit('unknown option %s' % k)
            o = cfg.opts[k]
            try:
                o.value = o.default if rest[0] == '--reset' else o.parse(v)
            except ValueError as e:
                sys.exit('%s: %s' % (k, e))
        cfg.save()
        return
    sys.exit('unknown arguments: %s' % ' '.join(rest))


if __name__ == '__main__':
    main()
