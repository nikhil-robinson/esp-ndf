#!/usr/bin/env python3
"""C header with the test PKI of tools/wl/pki for the board test apps (CA public key, server certificate DER, server private key).
usage: tls_header.py <pki dir> <out.h>"""
import sys, os
d, out = sys.argv[1], sys.argv[2]
def arr(name, b): return 'static const unsigned char %s[%d] = {%s};\n' % (name, len(b), ','.join('0x%02x' % x for x in b))
ca = bytes.fromhex(open(os.path.join(d, 'ca_pub.hex')).read().strip()); srv = open(os.path.join(d, 'server.der'), 'rb').read()
priv = bytes.fromhex(open(os.path.join(d, 'server_priv.hex')).read().strip()); other = bytes.fromhex(open(os.path.join(d, 'other_ca_pub.hex')).read().strip())
open(out, 'w').write('/* generated by tools/wl/tls_header.py from tools/wl/pki: TEST keys, never use outside the lab */\n' + arr('tls_ca_pub', ca) + arr('tls_other_ca_pub', other) + arr('tls_server_cert', srv) + arr('tls_server_priv', priv))
