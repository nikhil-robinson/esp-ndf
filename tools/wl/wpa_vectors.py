#!/usr/bin/env python3
"""Generate components/wifi/test_apps/wpa_unit/vectors.h with an independent implementation (hashlib / hmac / cryptography):
PMK, HMAC-SHA1, PTK, EAPOL-Key MIC, RFC 3394 unwrap, CCMP frames. Run it again after changing the cases; the header is committed."""
import hashlib, hmac, os, random
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

random.seed(80211)
rb = lambda n: bytes(random.randrange(256) for _ in range(n))
out = ['/* generated by tools/wl/wpa_vectors.py - do not edit */', '#include <stdint.h>']
def arr(name, b): out.append('static const uint8_t %s[%d] = { %s };' % (name, max(len(b), 1), ', '.join('0x%02x' % x for x in b) if b else '0'))

# PMK: IEEE 802.11i annex H.4 and a 63-character passphrase
pm = [(b'password', b'IEEE'), (b'ThisIsAPassword', b'ThisIsASSID'), (b'a' * 63, b'x' * 32)]
for i, (p, s) in enumerate(pm):
    arr('pmk_pass%d' % i, p + b'\0'); arr('pmk_ssid%d' % i, s); arr('pmk_out%d' % i, hashlib.pbkdf2_hmac('sha1', p, s, 4096, 32))
out.append('#define N_PMK %d' % len(pm))
# HMAC-SHA1 (RFC 2202 case 2 plus a key longer than the block)
hm = [(b'Jefe', b'what do ya want for nothing?'), (b'\xaa' * 80, b'Test Using Larger Than Block-Size Key - Hash Key First')]
for i, (k, d) in enumerate(hm): arr('hm_key%d' % i, k); arr('hm_dat%d' % i, d); arr('hm_out%d' % i, hmac.new(k, d, hashlib.sha1).digest())
out.append('#define N_HM %d' % len(hm))
# PTK
def prf(k, a, b, n):
    r = b''; i = 0
    while len(r) * 8 < n: r += hmac.new(k, a + b'\0' + b + bytes([i]), hashlib.sha1).digest(); i += 1
    return r[:n // 8]
pmk = rb(32); aa = rb(6); spa = rb(6); an = rb(32); sn = rb(32)
data = min(aa, spa) + max(aa, spa) + min(an, sn) + max(an, sn)
ptk = prf(pmk, b'Pairwise key expansion', data, 384)
for n, v in (('ptk_pmk', pmk), ('ptk_aa', aa), ('ptk_spa', spa), ('ptk_an', an), ('ptk_sn', sn), ('ptk_out', ptk)): arr(n, v)
# EAPOL-Key message 3 with a valid MIC
kck = ptk[:16]
body = bytes([2]) + (0x13ca).to_bytes(2, 'big') + (16).to_bytes(2, 'big') + (7).to_bytes(8, 'big') + an + bytes(16) + bytes(8) + bytes(8) + bytes(16) + (24).to_bytes(2, 'big') + rb(24)
fr = bytes([2, 3]) + len(body).to_bytes(2, 'big') + body
mic = hmac.new(kck, fr, hashlib.sha1).digest()[:16]
fr = fr[:81] + mic + fr[97:]
arr('eapol_kck', kck); arr('eapol_frame', fr)
# RFC 3394
kek = bytes(range(16))
for i, kd in enumerate((bytes.fromhex('00112233445566778899AABBCCDDEEFF'), bytes.fromhex('00112233445566778899AABBCCDDEEFF000102030405060708090A0B0C0D0E0F'))):
    arr('uw_in%d' % i, aes_key_wrap(kek, kd)); arr('uw_key%d' % i, kd)
arr('uw_kek', kek)
# CCMP: (header, payload) pairs; AAD and nonce built here from the 802.11 rules, independently of the C code
def ccmp(tk, hdr, pn, data):
    fc0, fc1 = hdr[0], hdr[1]; qos = fc0 & 0x80 and (fc0 & 0x0C) == 8; four = (fc1 & 3) == 3
    aad = bytes([fc0 & 0x8F, (fc1 & 0xC7) | 0x40]) + hdr[4:22] + bytes([hdr[22] & 0x0F, 0]) + (hdr[24:30] if four else b'')
    tid = 0
    if qos: q = 24 + (6 if four else 0); aad += bytes([hdr[q] & 0x0F, 0]); tid = hdr[q] & 0x0F
    nonce = bytes([tid]) + hdr[10:16] + pn.to_bytes(6, 'big')
    ct = AESCCM(tk, tag_length=8).encrypt(nonce, data, aad)
    ch = bytes([pn & 255, (pn >> 8) & 255, 0, 0x20, (pn >> 16) & 255, (pn >> 24) & 255, (pn >> 32) & 255, (pn >> 40) & 255])
    return ch + ct
tk = rb(16); arr('ccmp_tk', tk); cases = []
for i, (qos, four, n, pn) in enumerate([(0, 0, 0, 1), (0, 0, 1, 2), (0, 0, 15, 3), (1, 0, 16, 0x0102030405), (1, 0, 17, 5), (0, 1, 100, 6), (1, 1, 333, 7), (0, 0, 1500, 0xFFFFFFFFFF)]):
    fc0 = 0x88 if qos else 0x08; fc1 = 0x03 if four else 0x01
    hdr = bytes([fc0, fc1 | 0x08 | 0x10]) + bytes(2) + rb(6) + rb(6) + rb(6) + bytes([0x35, 0x12]) + (rb(6) if four else b'') + (bytes([0x05, 0]) if qos else b'')
    data = rb(n); arr('cc_hdr%d' % i, hdr); arr('cc_pt%d' % i, data); arr('cc_ct%d' % i, ccmp(tk, hdr, pn, data)); out.append('static const uint64_t cc_pn%d = 0x%xULL;' % (i, pn)); cases.append(i)
out.append('#define N_CC %d' % len(cases))
open(os.path.join(os.path.dirname(__file__), '..', '..', 'components', 'wifi', 'test_apps', 'wpa_unit', 'vectors.h'), 'w').write('\n'.join(out) + '\n')
