#!/usr/bin/env python3
"""Turn an ESP-IDF v6.1 register header (components/soc/esp32p4/register/hw_ver3/soc/<x>_reg.h) into a compact header
of facts: one `#define <NAME>_REG (<BASE> + off)` per register and `<FIELD>_R` (its register) / `<FIELD>_S` / `<FIELD>_W` per field.
The drivers use REG(), REG_FIELD(addr, <F>_S, <F>_W, v) and BIT(<F>_S). Usage:
    gen.py IDF_REG_H OUT_H BASE_MACRO BASE_ADDR [KEEP_REGEX]
KEEP_REGEX (optional) limits the output to names that match it (large blocks: ISP, EMAC). Not machine specific."""
import re, sys
src, out, base, addr = sys.argv[1:5]
keep = re.compile(sys.argv[5]) if len(sys.argv) > 5 else None
regs, fields, cur = [], [], None
for ln in open(src):
    m = re.match(r"#define (\w+_REG)\s+\(DR_REG_\w+_BASE \+ (0x[0-9a-fA-F]+)\)", ln)
    if m: regs.append((m[1], m[2])); cur = m[1]; continue
    m = re.match(r"/\*\* (\w+) : \w+(?:/\w+)*; bitpos: \[(\d+)(?::(\d+))?\]", ln)
    if m:
        hi = int(m[2]); lo = int(m[3]) if m[3] else hi
        fields.append((m[1], lo, hi - lo + 1, cur))
with open(out, "w") as o:
    o.write("/* generated by tools/p4_regs/gen.py from ESP-IDF v6.1 %s: register offsets and field positions (facts) */\n#pragma once\n" % src.split("/")[-1])
    o.write("#ifndef %s\n#define %s %s\n#endif\n" % (base, base, addr))
    for n, off in regs:
        if keep is None or keep.search(n): o.write("#define %s (%s + %s)\n" % (n, base, off))
    for n, lo, w, r in fields:
        if keep is None or keep.search(n): o.write("#define %s_R %s\n#define %s_S %d\n#define %s_W %d\n" % (n, r, n, lo, n, w))
print(out, len(regs), "registers", len(fields), "fields")
