#!/usr/bin/env python3
"""IDF soc_etm_source.h -> a header of the event / task ids only (facts). Usage: gen_etm.py IDF_SOC_ETM_SOURCE_H OUT_H"""
import re, sys
out = open(sys.argv[2], "w")
out.write("/* generated by tools/p4_regs/gen_etm.py from ESP-IDF v6.1 soc_etm_source.h: ETM event and task ids */\n#pragma once\n")
n = 0
for ln in open(sys.argv[1]):
    m = re.match(r"#define (\w+_(?:EVT|TASK)_\w+)\s+(\d+)", ln)
    if m: out.write("#define ETM_%s %s\n" % (m[1], m[2])); n += 1
print(sys.argv[2], n, "ids")
